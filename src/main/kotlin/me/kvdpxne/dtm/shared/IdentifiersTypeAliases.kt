 *
 * @since 0.1.0
 */
typealias ArenaUuid = UUID

/**
 * Represents a unique identifier for a game instance.
 *
 * @since 0.1.0
 */
typealias GameUuid = UUID

/**
 * Represents a unique identifier for tracking user or teammate statistics.
 *
 * @since 0.1.0
 */
typealias StatisticsUuid = UUID

/**
 * Represents a unique identifier for a team.
 *
 * @since 0.1.0
 */
typealias TeamUuid = UUID

/**
 * Represents a unique identifier for a specific monument position.
 *
 * @since 0.1.0
 */
typealias MonumentPositionUuid = UUID

/**
 * Represents a unique identifier for a minecraft player.
 *
 * @since 0.1.0
 */
typealias PlayerUuid = UUID

/**
 * Represents a unique identifier for a revival position.
 *
 * @since 0.1.0
 */
typealias RevivalPositionUuid = UUID

/**
 * Represents a unique identifier for a user's wallet.
 *
 * @since 0.1.0
 */
typealias WalletUuid = UUID

/**
 * Represents a unique identifier for a minecraft world.
 *
 * @since 0.1.0
 */
typealias WorldUuid = UUID